import { defineConfig } from "vite";
// Builds ../views.js (core screens) plus on-demand ../views_compare.js, ../views_farm.js, ../views_more.js, ../views_lab.js.
// Screens are written in JSX and drawn by Preact (3 KB gzipped; React was 72 KB). JSX is compiled by Vite's own esbuild, no plugin needed.
// Shared code (Preact, slots.js, …) goes to ../vchunk-*.js; names carry no hash so sw.js can precache them.
export default defineConfig({
  esbuild: { jsx: "automatic", jsxImportSource: "preact" },
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
  build: {
    outDir: "..", emptyOutDir: false, minify: true, sourcemap: false, target: "es2020",
    lib: { entry: { views: "src/views.jsx", views_compare: "src/views_compare.jsx", views_farm: "src/views_farm.jsx", views_more: "src/views_more.jsx", views_lab: "src/views_lab.jsx" }, formats: ["es"], fileName: (_f, name) => `${name}.js` },
    rollupOptions: { output: {
      banner: "/*! GENERATED by frontend/ (npm run build) - do not edit by hand */",
      chunkFileNames: "vchunk-[name].js",
      manualChunks: id => id.includes("node_modules") ? "preact" : (id.endsWith("slots.js") ? "slots" : undefined),
    } },
  },
});
