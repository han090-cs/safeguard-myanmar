"""Export the public contracts as JSON Schema and TypeScript declarations.

    python tools/export_types.py            # writes docs/schema/risk_objects.schema.json and docs/types/risk.d.ts

The Pydantic models in risk_engine/schemas.py are the single source of truth; the files written here are
generated and should not be edited by hand. The frontend (plain JS) can use the .d.ts through JSDoc
(`/** @type {import('./docs/types/risk').WhatMattersItem} */`) and a future map layer consumes the same objects.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from risk_engine.schemas import (Condition, EngineResult, Metric, OfficialWarning, ProviderStatus,  # noqa: E402
                                 RiskObject, WhatMattersItem)

MODELS = [EngineResult, RiskObject, WhatMattersItem, OfficialWarning, Condition, Metric, ProviderStatus]


def _ts(schema: dict, indent: str = "  ") -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(_ts(s, indent) for s in schema["anyOf"]))
    t = schema.get("type")
    if t == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(_ts(s, indent) for s in schema["prefixItems"]) + "]"
        inner = _ts(schema.get("items", {}), indent)
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        if "properties" in schema:
            return _obj(schema, indent)
        ap = schema.get("additionalProperties")
        return f"Record<string, {_ts(ap, indent)}>" if isinstance(ap, dict) and ap else "Record<string, unknown>"
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(t, "unknown")


def _obj(schema: dict, indent: str) -> str:
    req = set(schema.get("required", []))
    lines = ["{"]
    for name, prop in schema["properties"].items():
        doc = prop.get("description")
        if doc:
            lines.append(f"{indent}/** {doc} */")
        opt = "" if name in req else "?"
        lines.append(f"{indent}{name}{opt}: {_ts(prop, indent + '  ')};")
    lines.append(indent[:-2] + "}")
    return "\n".join(lines)


def build() -> tuple[dict, str]:
    defs: dict[str, dict] = {}
    for m in MODELS:
        sch = m.model_json_schema(ref_template="#/$defs/{model}")
        defs.update(sch.pop("$defs", {}))
        defs[m.__name__] = sch
    bundle = {"$schema": "https://json-schema.org/draft/2020-12/schema",
              "title": "Myanmar weather risk engine – public objects", "$defs": dict(sorted(defs.items()))}
    out = ["// GENERATED by tools/export_types.py from risk_engine/schemas.py – do not edit by hand.", ""]
    for name, sch in sorted(defs.items()):
        doc = (sch.get("description") or "").strip().replace("\n", "\n * ")
        if doc:
            out.append(f"/**\n * {doc}\n */")
        body = _obj(sch, "  ") if "properties" in sch else _ts(sch)
        out.append(f"export interface {name} {body}" if "properties" in sch else f"export type {name} = {body};")
        out.append("")
    return bundle, "\n".join(out)


if __name__ == "__main__":
    bundle, ts = build()
    (ROOT / "docs" / "schema").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "types").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "schema" / "risk_objects.schema.json").write_text(
        json.dumps(bundle, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (ROOT / "docs" / "types" / "risk.d.ts").write_text(ts, encoding="utf-8")
    print(f"wrote {len(bundle['$defs'])} types")
